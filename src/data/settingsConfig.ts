// Função auxiliar para obter valores padrão de uma categoria
export function getDefaultValues(categories: ConfigCategory[]): Record<string, Record<string, Record<string, unknown>>> {
  const defaults: Record<string, Record<string, Record<string, unknown>>> = {};

  for (const category of categories) {
    defaults[category.key] = {};
    for (const subcategory of category.subcategories) {
      defaults[category.key][subcategory.key] = {};
      for (const field of subcategory.fields) {
        defaults[category.key][subcategory.key][field.key] = field.defaultValue;
      }
    }
  }

  return defaults;
}

// Função para buscar configurações
export function searchSettings(
  categories: ConfigCategory[],
  query: string
): Array<{
  categoryKey: string;
  subcategoryKey: string;
  fieldKey?: string;
  matchType: 'category' | 'subcategory' | 'field';
  matchText: string;
}> {
  const results: Array<{
    categoryKey: string;
    subcategoryKey: string;
    fieldKey?: string;
    matchType: 'category' | 'subcategory' | 'field';
    matchText: string;
  }> = [];

  const lowerQuery = query.toLowerCase();

  for (const category of categories) {
    // Busca na categoria
    if (category.name.toLowerCase().includes(lowerQuery)) {
      results.push({
        categoryKey: category.key,
        subcategoryKey: category.subcategories[0]?.key || '',
        matchType: 'category',
        matchText: category.name,
      });
    }

    for (const subcategory of category.subcategories) {
      // Busca na subcategoria
      if (subcategory.name.toLowerCase().includes(lowerQuery)) {
        results.push({
          categoryKey: category.key,
          subcategoryKey: subcategory.key,
          matchType: 'subcategory',
          matchText: subcategory.name,
        });
      }

      for (const field of subcategory.fields) {
        // Busca nos campos
        if (
          field.name.toLowerCase().includes(lowerQuery) ||
          field.description.toLowerCase().includes(lowerQuery)
        ) {
          results.push({
            categoryKey: category.key,
            subcategoryKey: subcategory.key,
            fieldKey: field.key,
            matchType: 'field',
            matchText: field.name,
          });
        }
      }
    }
  }

  return results;
}
