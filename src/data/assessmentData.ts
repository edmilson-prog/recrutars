/**
 * Obtém a dimensão pelo ID
 */
export function getDimensionById(id: string): AssessmentDimension | undefined {
  return assessmentDimensions.find(d => d.id === id);
}

/**
 * Obtém a categoria pelo ID
 */
export function getCategoryById(id: string): AssessmentCategory | undefined {
  return assessmentCategories.find(c => c.id === id);
}

/**
 * Obtém categorias por dimensão
 */
export function getCategoriesByDimension(dimensionId: string): AssessmentCategory[] {
  return assessmentCategories.filter(c => c.dimensionId === dimensionId);
}

/**
 * Obtém perguntas por categoria
 */
export function getQuestionsByCategory(categoryId: string): AssessmentQuestion[] {
  return assessmentQuestions.filter(q => q.categoryId === categoryId);
}

/**
 * Obtém a dimensão de uma pergunta
 */
export function getQuestionDimension(question: AssessmentQuestion): AssessmentDimension | undefined {
  const category = getCategoryById(question.categoryId);
  if (!category) return undefined;
  return getDimensionById(category.dimensionId);
}
